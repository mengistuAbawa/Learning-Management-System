BEGIN;

-- QUIZZES
CREATE TABLE IF NOT EXISTS quizzes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    time_limit_minutes INTEGER NOT NULL DEFAULT 30,
    passing_score NUMERIC(5,2) NOT NULL DEFAULT 50,
    max_attempts INTEGER NOT NULL DEFAULT 3,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE quizzes ADD COLUMN IF NOT EXISTS title VARCHAR(200);
ALTER TABLE quizzes ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE quizzes ADD COLUMN IF NOT EXISTS time_limit_minutes INTEGER NOT NULL DEFAULT 30;
ALTER TABLE quizzes ADD COLUMN IF NOT EXISTS passing_score NUMERIC(5,2) NOT NULL DEFAULT 50;
ALTER TABLE quizzes ADD COLUMN IF NOT EXISTS max_attempts INTEGER NOT NULL DEFAULT 3;
ALTER TABLE quizzes ADD COLUMN IF NOT EXISTS is_published BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE quizzes ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE quizzes ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- QUESTIONS
CREATE TABLE IF NOT EXISTS quiz_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
    question_text TEXT NOT NULL,
    points NUMERIC(8,2) NOT NULL DEFAULT 1,
    position INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (quiz_id, position)
);

ALTER TABLE quiz_questions ADD COLUMN IF NOT EXISTS question_text TEXT;
ALTER TABLE quiz_questions ADD COLUMN IF NOT EXISTS points NUMERIC(8,2) NOT NULL DEFAULT 1;
ALTER TABLE quiz_questions ADD COLUMN IF NOT EXISTS position INTEGER NOT NULL DEFAULT 1;

-- OPTIONS
CREATE TABLE IF NOT EXISTS quiz_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES quiz_questions(id) ON DELETE CASCADE,
    option_text TEXT NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    position INTEGER NOT NULL DEFAULT 1,
    UNIQUE (question_id, position)
);

ALTER TABLE quiz_options ADD COLUMN IF NOT EXISTS option_text TEXT;
ALTER TABLE quiz_options ADD COLUMN IF NOT EXISTS is_correct BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE quiz_options ADD COLUMN IF NOT EXISTS position INTEGER NOT NULL DEFAULT 1;

-- ATTEMPTS
CREATE TABLE IF NOT EXISTS quiz_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    attempt_number INTEGER NOT NULL DEFAULT 1,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at TIMESTAMPTZ,
    score NUMERIC(8,2),
    total_points NUMERIC(8,2),
    passed BOOLEAN,
    status VARCHAR(20) NOT NULL DEFAULT 'in_progress'
      CHECK (status IN ('in_progress', 'submitted', 'expired')),
    UNIQUE (quiz_id, student_id, attempt_number)
);

ALTER TABLE quiz_attempts ADD COLUMN IF NOT EXISTS attempt_number INTEGER NOT NULL DEFAULT 1;
ALTER TABLE quiz_attempts ADD COLUMN IF NOT EXISTS started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE quiz_attempts ADD COLUMN IF NOT EXISTS submitted_at TIMESTAMPTZ;
ALTER TABLE quiz_attempts ADD COLUMN IF NOT EXISTS score NUMERIC(8,2);
ALTER TABLE quiz_attempts ADD COLUMN IF NOT EXISTS total_points NUMERIC(8,2);
ALTER TABLE quiz_attempts ADD COLUMN IF NOT EXISTS passed BOOLEAN;
ALTER TABLE quiz_attempts ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'in_progress';

-- ANSWERS
CREATE TABLE IF NOT EXISTS quiz_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES quiz_questions(id) ON DELETE CASCADE,
    option_id BIGINT REFERENCES quiz_options(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (attempt_id, question_id)
);

ALTER TABLE quiz_answers ADD COLUMN IF NOT EXISTS option_id BIGINT REFERENCES quiz_options(id) ON DELETE SET NULL;

-- ASSIGNMENTS
CREATE TABLE IF NOT EXISTS assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    due_at TIMESTAMPTZ,
    max_points NUMERIC(8,2) NOT NULL DEFAULT 100,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE assignments ADD COLUMN IF NOT EXISTS title VARCHAR(200);
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS due_at TIMESTAMPTZ;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS max_points NUMERIC(8,2) NOT NULL DEFAULT 100;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS is_published BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE assignments ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'assignments'
          AND column_name = 'instructions'
    ) THEN
        UPDATE assignments
        SET description = instructions
        WHERE description IS NULL;

        ALTER TABLE assignments ALTER COLUMN instructions DROP NOT NULL;
    END IF;
END $$;

-- SUBMISSIONS
CREATE TABLE IF NOT EXISTS assignment_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    submission_text TEXT,
    submission_url TEXT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    grade NUMERIC(8,2),
    feedback TEXT,
    graded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    graded_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'submitted'
      CHECK (status IN ('submitted', 'graded', 'late')),
    UNIQUE (assignment_id, student_id)
);

ALTER TABLE assignment_submissions ADD COLUMN IF NOT EXISTS submission_text TEXT;
ALTER TABLE assignment_submissions ADD COLUMN IF NOT EXISTS submission_url TEXT;
ALTER TABLE assignment_submissions ADD COLUMN IF NOT EXISTS submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE assignment_submissions ADD COLUMN IF NOT EXISTS grade NUMERIC(8,2);
ALTER TABLE assignment_submissions ADD COLUMN IF NOT EXISTS feedback TEXT;
ALTER TABLE assignment_submissions ADD COLUMN IF NOT EXISTS graded_by BIGINT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE assignment_submissions ADD COLUMN IF NOT EXISTS graded_at TIMESTAMPTZ;
ALTER TABLE assignment_submissions ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'submitted';

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'assignment_submissions'
          AND column_name = 'file_url'
    ) THEN
        UPDATE assignment_submissions
        SET submission_url = file_url
        WHERE submission_url IS NULL;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'assignment_submissions'
          AND column_name = 'score'
    ) THEN
        UPDATE assignment_submissions
        SET grade = score
        WHERE grade IS NULL;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_quizzes_course ON quizzes(course_id);
CREATE INDEX IF NOT EXISTS idx_questions_quiz ON quiz_questions(quiz_id);
CREATE INDEX IF NOT EXISTS idx_options_question ON quiz_options(question_id);
CREATE INDEX IF NOT EXISTS idx_attempts_student ON quiz_attempts(student_id, quiz_id);
CREATE INDEX IF NOT EXISTS idx_assignments_course ON assignments(course_id);
CREATE INDEX IF NOT EXISTS idx_submissions_assignment ON assignment_submissions(assignment_id);
CREATE INDEX IF NOT EXISTS idx_submissions_student ON assignment_submissions(student_id);

COMMIT;