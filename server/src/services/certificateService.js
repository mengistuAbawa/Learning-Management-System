/**
 * Certificate Service
 * Handles certificate eligibility checking, issuance, and verification logic.
 * All database queries are parameterized for security.
 */

const { pool } = require("../config/db");
const crypto = require("crypto");

/**
 * Check if a student is eligible for a certificate in a course.
 * Eligibility requires:
 * 1. Student is enrolled in the course
 * 2. Enrollment status is 'completed'
 * 3. All required lessons are completed
 *
 * @param {number|string} studentId - Authenticated student's ID
 * @param {number|string} courseId - Course ID to check
 * @returns {Promise<{eligible: boolean, enrollment: object|null, reason?: string}>}
 */
async function checkEligibility(studentId, courseId) {
  try {
    // Verify enrollment exists and check completion status
    const enrollmentResult = await pool.query(
      `SELECT
         e.id AS enrollment_id,
         e.status,
         e.created_at,
         e.completed_at,
         c.id AS course_id,
         c.title AS course_title,
         COUNT(l.id)::int AS total_lessons,
         COUNT(l.id) FILTER (WHERE lp.completed = TRUE)::int AS completed_lessons
       FROM enrollments e
       JOIN courses c ON c.id = e.course_id
       LEFT JOIN modules m ON m.course_id = c.id
       LEFT JOIN lessons l ON l.module_id = m.id
       LEFT JOIN lesson_progress lp
         ON lp.enrollment_id = e.id AND lp.lesson_id = l.id
       WHERE e.student_id = $1 AND e.course_id = $2
       GROUP BY e.id, e.status, e.created_at, e.completed_at, c.id, c.title`,
      [studentId, courseId]
    );

    if (enrollmentResult.rows.length === 0) {
      return {
        eligible: false,
        enrollment: null,
        reason: "Not enrolled in this course",
      };
    }

    const enrollment = enrollmentResult.rows[0];

    // Check if enrollment is completed
    if (enrollment.status !== "completed") {
      const completionPercent =
        enrollment.total_lessons > 0
          ? Math.round(
              (100 * enrollment.completed_lessons) / enrollment.total_lessons
            )
          : 0;

      return {
        eligible: false,
        enrollment,
        reason: `Course not yet complete. Progress: ${enrollment.completed_lessons} of ${enrollment.total_lessons} lessons (${completionPercent}%)`,
      };
    }

    // Enrollment is completed - eligible for certificate
    return {
      eligible: true,
      enrollment,
    };
  } catch (error) {
    console.error("Certificate eligibility check failed:", error);
    throw error;
  }
}

/**
 * Issue a certificate for an eligible student/course combination.
 * If certificate already exists, returns existing one (idempotent).
 * Uses database unique constraint to prevent race condition duplicates.
 *
 * @param {number|string} studentId - Student ID
 * @param {number|string} courseId - Course ID
 * @returns {Promise<{certificate: object, isNew: boolean}>}
 */
async function issueCertificate(studentId, courseId) {
  const client = await pool.connect();

  try {
    await client.query("BEGIN");

    // Get enrollment ID and verify eligibility
    const enrollmentResult = await client.query(
      `SELECT e.id AS enrollment_id, e.status, e.student_id
       FROM enrollments e
       WHERE e.student_id = $1 AND e.course_id = $2
         AND e.status = 'completed'
       LIMIT 1`,
      [studentId, courseId]
    );

    if (enrollmentResult.rows.length === 0) {
      await client.query("ROLLBACK");
      const error = new Error("Student is not eligible for a certificate");
      error.statusCode = 403;
      throw error;
    }

    const enrollmentId = enrollmentResult.rows[0].enrollment_id;

    // Try to get existing certificate
    const existingCert = await client.query(
      `SELECT id, enrollment_id, certificate_code, issued_at
       FROM certificates
       WHERE enrollment_id = $1
       LIMIT 1`,
      [enrollmentId]
    );

    if (existingCert.rows.length > 0) {
      // Certificate already exists, return it
      await client.query("COMMIT");
      return {
        certificate: existingCert.rows[0],
        isNew: false,
      };
    }

    // Create new certificate
    // UUID is generated by PostgreSQL (gen_random_uuid()), not by Node
    const certResult = await client.query(
      `INSERT INTO certificates (enrollment_id, certificate_code, issued_at)
       VALUES ($1, gen_random_uuid(), NOW())
       RETURNING id, enrollment_id, certificate_code, issued_at`,
      [enrollmentId]
    );

    await client.query("COMMIT");

    return {
      certificate: certResult.rows[0],
      isNew: true,
    };
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

/**
 * Get a student's certificate details by certificate ID.
 * Verifies the student owns the certificate before returning.
 *
 * @param {number|string} certificateId - Certificate ID
 * @param {number|string} studentId - Student ID (for verification)
 * @returns {Promise<object|null>}
 */
async function getCertificateDetails(certificateId, studentId) {
  const result = await pool.query(
    `SELECT
       cert.id,
       cert.enrollment_id,
       cert.certificate_code,
       cert.issued_at,
       e.student_id,
       e.course_id,
       u.full_name AS student_name,
       c.title AS course_title,
       c.instructor_id,
       instr.full_name AS instructor_name
     FROM certificates cert
     JOIN enrollments e ON e.id = cert.enrollment_id
     JOIN users u ON u.id = e.student_id
     JOIN courses c ON c.id = e.course_id
     JOIN users instr ON instr.id = c.instructor_id
     WHERE cert.id = $1 AND e.student_id = $2
     LIMIT 1`,
    [certificateId, studentId]
  );

  return result.rows[0] || null;
}

/**
 * Get all certificates for a student.
 *
 * @param {number|string} studentId - Student ID
 * @returns {Promise<Array>}
 */
async function getStudentCertificates(studentId) {
  const result = await pool.query(
    `SELECT
       cert.id,
       cert.enrollment_id,
       cert.certificate_code,
       cert.issued_at,
       e.student_id,
       e.course_id,
       u.full_name AS student_name,
       c.title AS course_title,
       c.thumbnail_url,
       c.level,
       instr.full_name AS instructor_name
     FROM certificates cert
     JOIN enrollments e ON e.id = cert.enrollment_id
     JOIN users u ON u.id = e.student_id
     JOIN courses c ON c.id = e.course_id
     JOIN users instr ON instr.id = c.instructor_id
     WHERE e.student_id = $1
     ORDER BY cert.issued_at DESC`,
    [studentId]
  );

  return result.rows;
}

/**
 * Verify a certificate by its code (public endpoint).
 * Returns minimal information suitable for public sharing.
 *
 * @param {string} code - Certificate code (UUID string)
 * @returns {Promise<{valid: boolean, certificate?: object}>}
 */
async function verifyCertificateCode(code) {
  // Validate UUID format (basic check)
  const uuidRegex =
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
  if (!uuidRegex.test(code)) {
    return {
      valid: false,
    };
  }

  const result = await pool.query(
    `SELECT
       cert.certificate_code,
       cert.issued_at,
       u.full_name AS student_name,
       c.title AS course_title,
       c.level,
       instr.full_name AS instructor_name
     FROM certificates cert
     JOIN enrollments e ON e.id = cert.enrollment_id
     JOIN users u ON u.id = e.student_id
     JOIN courses c ON c.id = e.course_id
     JOIN users instr ON instr.id = c.instructor_id
     WHERE cert.certificate_code = $1
     LIMIT 1`,
    [code]
  );

  if (result.rows.length === 0) {
    return {
      valid: false,
    };
  }

  const cert = result.rows[0];
  return {
    valid: true,
    certificate: {
      student_name: cert.student_name,
      course_title: cert.course_title,
      course_level: cert.level,
      instructor_name: cert.instructor_name,
      issued_at: cert.issued_at,
      code: cert.certificate_code,
    },
  };
}

/**
 * Get eligibility info for a student in a specific course.
 * Used by frontend to show completion status and certificate actions.
 *
 * @param {number|string} studentId - Student ID
 * @param {number|string} courseId - Course ID
 * @returns {Promise<object>}
 */
async function getCompletionStatus(studentId, courseId) {
  const enrollmentResult = await pool.query(
    `SELECT
       e.id AS enrollment_id,
       e.status,
       e.created_at,
       e.completed_at,
       c.id AS course_id,
       c.title,
       COUNT(l.id)::int AS total_lessons,
       COUNT(l.id) FILTER (WHERE lp.completed = TRUE)::int AS completed_lessons,
       COUNT(CASE WHEN cert.id IS NOT NULL THEN 1 END)::int AS has_certificate
     FROM enrollments e
     JOIN courses c ON c.id = e.course_id
     LEFT JOIN modules m ON m.course_id = c.id
     LEFT JOIN lessons l ON l.module_id = m.id
     LEFT JOIN lesson_progress lp
       ON lp.enrollment_id = e.id AND lp.lesson_id = l.id
     LEFT JOIN certificates cert ON cert.enrollment_id = e.id
     WHERE e.student_id = $1 AND e.course_id = $2
     GROUP BY e.id, e.status, e.created_at, e.completed_at, c.id, c.title`,
    [studentId, courseId]
  );

  if (enrollmentResult.rows.length === 0) {
    return {
      enrolled: false,
      completed: false,
      has_certificate: false,
    };
  }

  const data = enrollmentResult.rows[0];
  const completionPercent =
    data.total_lessons > 0
      ? Math.round((100 * data.completed_lessons) / data.total_lessons)
      : 0;

  return {
    enrolled: true,
    completed: data.status === "completed",
    completion_percentage: completionPercent,
    completed_lessons: data.completed_lessons,
    total_lessons: data.total_lessons,
    has_certificate: data.has_certificate > 0,
  };
}

