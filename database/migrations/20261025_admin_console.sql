BEGIN;

-- Additive metadata for reviewing user applications and describing categories.
ALTER TABLE course_categories
    ADD COLUMN IF NOT EXISTS description TEXT;

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS approval_reviewed_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS approval_reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS approval_reason TEXT;

ALTER TABLE notifications
    ADD COLUMN IF NOT EXISTS announcement_id BIGINT
    REFERENCES announcements(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_notifications_announcement
    ON notifications(announcement_id, user_id)
    WHERE announcement_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS idx_notifications_announcement_user
    ON notifications(announcement_id, user_id)
    WHERE announcement_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS admin_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(120) NOT NULL,
    resource VARCHAR(120) NOT NULL,
    resource_id VARCHAR(120),
    http_method VARCHAR(10) NOT NULL,
    response_status INTEGER NOT NULL,
    ip_address INET,
    user_agent VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_created
    ON admin_audit_logs(created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_actor
    ON admin_audit_logs(actor_user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_action
    ON admin_audit_logs(action, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_resource
    ON admin_audit_logs(resource, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_users_instructor_review
    ON users(approval_status, created_at DESC, id DESC)
    WHERE role = 'instructor';
CREATE INDEX IF NOT EXISTS idx_enrollments_created
    ON enrollments(created_at DESC, id DESC);

COMMIT;
